# ## 一、文件在做什么

# **Mini Project 1：命令行 Todo List** —— 一个靠 `input()` 交互、用 `while True` 循环驱动的内存版待办清单。特点是：数据不落盘（退出即丢），功能函数全部通过**全局变量 `tasks`** 而不是参数来读写数据。

# ## 二、数据模型（第 2–11 行）

# ```python
# tasks=[
#     {"task": "今日打卡", "done": False},
#     {"task": "今日学习", "done": True}
# ]
# ```

# `tasks` 是**模块级全局列表**，元素是 `{"task": 任务名, "done": 布尔}`。它没有放在任何函数里，所以 `todo_list` / `get_tasks` / `get_details` 三个函数都能直接改它。

# ## 三、各函数运行逻辑

# ### 1. `todo_list()` 第 13–23 行 —— 对应主菜单「5.待办清单」
# 1. 打印 `---代办清单---`；
# 2. `if len(tasks)==0` → 打印「暂无代办事项」并 `return`（提前结束，避免空列表还去跑 for）；
# 3. `enumerate(tasks, start=1)` 从 1 开始编号，按 `done` 取 `[√]` 或 `[ ]`，输出 `序号. [状态] 任务名`。
# 这是一个**纯只读**函数，不改数据。

# ### 2. `get_tasks()` 第 27–34 行 —— 对应主菜单「2.添加」
# 1. `input("请输入代办事项")` 拿任务名，直接塞进新字典 `works`（`done` 固定为 `False`）；
# 2. `tasks.append(works)` 追加到全局列表；
# 3. 打印「添加成功」。
# 只有「增」，**不做任何输入校验**。

# ### 3. `get_details()` 第 38–74 行 —— 主菜单「1/3/4」共用的二级菜单
# 1. **前置确认**（第 39–41 行）：先打印「点击查看任务(请输入yes)」，再 `if input()=="yes": print(tasks)`。输入 `yes` 才以 Python 原始格式（`[{'task': '今日打卡', 'done': False}, ...]`）打印列表；
# 2. 随后进入 `while True` 死循环，每一轮：
#    - 先用 `for` 重新打印清单，格式是 `序号.任务名,完成状态：True/False`；
#    - 打印子菜单「接下来你想要？(1)标记完成任务 (2)删除任务 (3)修改任务 (4)退出」；
#    - `choice = input("请输入你的选择：")`，分四路：
#      - `"1"` 标记完成：`int(input(...))` 取序号 → `1 <= task_index <= len(tasks)` 校验 → `tasks[task_index-1]["done"]=True`；
#      - `"2"` 删除：同样取序号 → `del tasks[task_index-1]`；
#      - `"3"` 修改：同样取序号 → 再 `input` 新内容 → `tasks[task_index-1]["task"]=new_task`；
#      - `"4"` 退出：打印「退出任务管理」并 `break`，**只跳出子循环，回到 `main()` 的菜单**；
#      - 序号越界统一走 `else` → 「输入序号错误，请重新输入」，然后自然进入下一轮循环（清单会重新打印）。

# ### 4. `main()` 第 77–93 行 —— 顶层菜单，程序入口

# ## 四、潜在 Bug

# ### 🔴 会崩溃 / 会误退出的（最该先修）

# **Bug 1｜`int(input(...))` 没有异常处理 —— 第 51、58、65 行**
# 三个分支都是 `task_index=int(input("请输入...序号："))`。只要用户输入字母、符号、中文序号、或者**直接按回车**，`int()` 立刻抛 `ValueError: invalid literal for int() with base 10: '...'`，因为没有 `try/except`，整个程序会带着 traceback 退出，**内存里的任务全部丢失**。
# 修复方向：抽一个安全读取函数，例如
# ```python
# def read_index(prompt):
#     try:
#         return int(input(prompt))
#     except ValueError:
#         print("请输入数字序号")
#         return None
# ```
# 调用处判断 `if task_index is None: continue`。

# **Bug 2｜`main()` 用 `else` 兜底退出 —— 第 79、91–93 行**
# 菜单写了 6 个选项，但只实现了 `1`–`5`，`"6"` 没有任何分支。于是：
# - 输入 `"6"` 能退出（**歪打正着**）；
# - 但输入 `"0"`、`"7"`、`"q"`、全角数字 `"１"`、甚至**回车空输入**，也会打印「退出任务管理」并 `break` —— 用户只是按错一下，程序就直接关了，且没有任何"输入有误"的提示。
# 修复方向：显式写 `elif choice=="6": break`，并把 `else` 改成「输入有误，请重新选择」+ `continue`。

# ### 🟡 逻辑 / 交互不一致

# **Bug 3｜`get_details()` 的 `choice` 没有 `else` —— 第 50–74 行之间**
# 子菜单输入 `"5"`、`"abc"`、空字符串时，四个 `if/elif` 都不匹配，函数**什么都不做就进入下一轮**，表现成菜单被反复刷新、看起来像卡死。它和 Bug 2 的行为正好相反（一个静默重刷、一个直接退出），两处都不提示，体验很割裂。

# **Bug 4｜菜单语义与实现不符：3「标记」、4「删除」其实都是同一个入口 —— 第 85–88 行**
# 菜单文字承诺"直接标记/直接删除"，实际三个选项都只是打开 `get_details()` 子菜单，用户还得在二级菜单里再选一次 1/2/3。这属于**两级菜单 + 重复入口**：入口冗余、层级绕、容易误操作。建议把「标记/删除/修改」各拆成独立函数，或者把 1/3/4 合并为一个「管理任务」入口。

# **Bug 5｜第 39–41 行的「请输入 yes」是多余步骤 —— 第 39–41 行**
# - 输 `yes` 只多打印一行原始 `tasks`，不输 `yes` 也会照常进入子菜单，这个分支几乎无意义（`print(tasks)` 是调试残留）；
# - 它还会消耗一次输入：用户在这里误输内容并不会被当成菜单选项，容易困惑。

# **Bug 6｜空输入不校验 —— 第 29、67 行**
# - `get_tasks()` 直接回车会添加 `{"task": "", "done": False}`，清单里出现一条空白待办；
# - 修改分支可以输入空字符串，把任务名改成空。
# 修复方向：`name = input(...).strip()` 后 `if not name: print("内容不能为空"); return`。

# **Bug 7｜列表为空时的提示不准确 —— 第 52、59、66 行的 `else`**
# `tasks` 为空（比如刚把任务全删光）时，输入任何序号都会只提示「输入序号错误，请重新输入」，而不是「当前没有任务可操作」。虽然 `1 <= task_index <= len(tasks)` 恒为 False 不会崩，但提示是误导性的。

# **Bug 8｜提示文字与结果挤在同一行 —— 第 29 + 34 行、第 80 行**
# `input("请输入代办事项")` 的提示不带换行，紧接着 `print("添加成功")`，终端会显示成 `请输入代办事项添加成功`；`main()` 的 `input("请输入")` 同样会和上一行菜单、下一行提示粘连（例如 `请输入点击查看任务(请输入yes)`）。交互上略显脏。给提示加 `\n` 或把提示单独 `print` 出来即可。

